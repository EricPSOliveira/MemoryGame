public class Sizes {
    int widthCard;
    int heightCard;
    int widthFrame;
    int heightFrame;

    public Sizes(){
        this.widthFrame = 1600;
        this.heightFrame = 1100;
        this.widthCard = 200;
        this.heightCard = 300;
    }



    public int getWidthCard() {
        return widthCard;
    }

    public int getHeightCard() {
        return heightCard;
    }

    public int getWidthFrame() {
        return widthFrame;
    }

    public int getHeightFrame() {
        return heightFrame;
    }




}
